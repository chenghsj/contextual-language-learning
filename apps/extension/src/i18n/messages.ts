export type UiLocale = keyof typeof messages;
export type MessageKey = keyof typeof messages.en;
export type MessageParams = Readonly<Record<string, string | number>>;

export function translate(locale: UiLocale, key: MessageKey, params: MessageParams = {}): string {
  const template: string = messages[locale][key] ?? messages.en[key];
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}
